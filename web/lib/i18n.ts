const dicts: Record<Lang, Dict> = { ko, en, "zh-tw": zh };

export function t(lang: Lang): Dict {
  return dicts[lang];
}

export function isLang(value: string): value is Lang {
  return (langs as readonly string[]).includes(value);
}

// When the last collection ran, in each language's own time zone; English pages use UTC
export function updatedAt(lang: Lang, ms: number) {
  const { intl, zone } = locales[lang];
  const opts: Intl.DateTimeFormatOptions = { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit", hourCycle: "h23", timeZone: zone };
  if (lang === "en") return `${new Intl.DateTimeFormat(intl, opts).format(ms)} UTC`;
  const text = new Intl.DateTimeFormat(intl, { ...opts, month: "long" }).format(ms);
  return lang === "zh-tw" ? `${text}（台灣時間）` : text;
}
